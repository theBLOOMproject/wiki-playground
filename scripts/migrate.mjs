// One-off: converts scripts/baseline.html (the original hand-written index.html)
// into content/ markdown + src/template.html. Safe to delete after migration.
import fs from "node:fs";
import path from "node:path";
import * as cheerio from "cheerio";

const ROOT = path.resolve(import.meta.dirname, "..");
const src = fs.readFileSync(path.join(ROOT, "scripts/baseline.html"), "utf8");
const $ = cheerio.load(src, { decodeEntities: true });
const out = (rel, text) => {
  const f = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, text);
};

// ---------- Template ----------
const START = '<div class="content" id="content">\n';
const END = "\n    </div>\n  </main>";
const a = src.indexOf(START) + START.length, b = src.indexOf(END, a);
if (a < START.length || b < 0) throw new Error("couldn't find article region");
let template = src.slice(0, a) + "<!-- ARTICLES -->" + src.slice(b);
const secRe = /var SECTIONS = (\[.*?\]);\n/;
const SECTIONS = JSON.parse(secRe.exec(template)[1]);
template = template.replace(secRe, "var SECTIONS = /* SECTIONS */[];\n");
template = template.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n<!-- Generated by `npm run build` from src/template.html and content/. Edit those files, not index.html. -->\n");
out("src/template.html", template);

// ---------- site.yml ----------
const q = (s) => JSON.stringify(s);
let yml = `# Site structure: sections and page order for the sidebar, home outline, and next/previous links.
# Each page id must match a file in content/pages/<id>.md.
# nav = the short label shown in the sidebar.  sub: true = indented under the page above it.
# single: true = the section has just one page and no sub-list in the sidebar.

sections:\n`;
for (const s of SECTIONS) {
  yml += `  - title: ${q(s.title)}\n`;
  if (s.single) yml += `    single: true\n`;
  yml += `    pages:\n`;
  for (const [id, nav, sub] of s.pages) {
    yml += `      - id: ${id}\n        nav: ${q(nav)}\n`;
    if (sub) yml += `        sub: true\n`;
  }
  yml += "\n";
}
yml += `# Pages that exist but aren't in the sidebar list or reading order.\nunlisted:\n  - review-notes\n`;
out("content/site.yml", yml);

// ---------- HTML → markdown ----------
const cls = (n) => ($(n).attr("class") || "").split(/\s+/).filter(Boolean);
const escText = (t) => t.replace(/([\\`*_[\]{}<])/g, "\\$1");

function wrap(mark, inner) {
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(inner);
  return m[2] ? `${m[1]}${mark}${m[2]}${mark}${m[3]}` : inner;
}

function noteKind(n) {
  const c = cls(n);
  const label = $(n).children("b").first().text().trim();
  const map = {
    "flag-check": { Check: "check", Verify: "verify" },
    "flag-team": { Team: "team", Gap: "gap" },
    "flag-new": { "New source": "new", Added: "added" },
  };
  for (const k of Object.keys(map)) if (c.includes(k)) return map[k][label] || fail(`unknown label ${label} for ${k}`);
  fail("unknown flag " + c.join(" "));
}
function fail(m) { throw new Error(m); }

function inl(node) {
  return $(node).contents().toArray().map(inlNode).join("");
}
function inlNode(n) {
  if (n.type === "text") return escText(n.data);
  if (n.type !== "tag") return "";
  const c = cls(n);
  switch (n.name) {
    case "strong": case "b": return wrap("**", inl(n));
    case "em": case "i": return wrap("*", inl(n));
    case "a": {
      const href = $(n).attr("href");
      return `[${inl(n)}](${/[\s()]/.test(href) ? `<${href}>` : href})`;
    }
    case "span":
      if (c.includes("edw")) return " ";
      if (c.includes("src")) return `{src: ${inl(n).trim()}}`;
      if (c.includes("flag")) {
        const kids = $(n).contents().toArray();
        const rest = kids.slice(1).map(inlNode).join("").replace(/^\s+/, "");
        return `{${noteKind(n)}: ${rest.trim()}}`;
      }
  }
  fail(`unhandled inline <${n.name} class="${c.join(" ")}">`);
}

function lineSafe(s) {
  return s.replace(/^(\d+)\. /, "$1\\. ").replace(/^([-+>#:]) /, "\\$1 ");
}

function list(n, depth = 0) {
  const ordered = n.name === "ol";
  return $(n).children("li").toArray().map((li, i) => {
    const marker = ordered ? `${i + 1}. ` : "- ";
    const pad = " ".repeat(marker.length);
    const own = $(li).contents().toArray().filter((k) => !(k.type === "tag" && (k.name === "ul" || k.name === "ol")));
    const text = own.map(inlNode).join("").trim();
    const nested = $(li).children("ul, ol").toArray().map((sub) => list(sub, depth + 1).replace(/^/gm, pad));
    return marker + lineSafe(text) + (nested.length ? "\n" + nested.join("\n") : "");
  }).join("\n");
}

function table(t) {
  const row = (tr) => "| " + $(tr).children("th, td").toArray().map((c) => inl(c).trim().replace(/\|/g, "\\|")).join(" | ") + " |";
  const head = $(t).find("thead tr").first();
  const cols = head.children().length;
  const body = $(t).find("tbody tr").toArray().map(row);
  return [row(head), "|" + " --- |".repeat(cols), ...body].join("\n");
}

const images = [];
function block(n, page) {
  if (n.type === "text") { if (n.data.trim()) fail(`stray text in ${page}: ${n.data.slice(0, 40)}`); return null; }
  if (n.type !== "tag") return null;
  const c = cls(n);
  const box = (name, body) => `::: ${name}\n${body}\n:::`;
  switch (n.name) {
    case "h1": return null; // becomes front matter title
    case "h2": return "## " + inl(n).trim();
    case "h3": return "### " + inl(n).trim();
    case "p": {
      const text = lineSafe(inl(n).trim());
      for (const k of ["lead", "lead-strong", "sources"]) if (c.includes(k)) return box(k, text);
      return text;
    }
    case "ul": return list(n);
    case "ol":
      if (c.includes("tl")) {
        const items = $(n).children("li").toArray().map((li, i) => {
          const when = $(li).children("span.when").first();
          const rest = $(li).contents().toArray().filter((k) => k !== when[0]).map(inlNode).join("").trim();
          return `${i + 1}. **${inl(when[0]).trim()}** ${rest}`;
        });
        return box("timeline", items.join("\n"));
      }
      return list(n);
    case "section":
      if (c.includes("keypoints")) return box("keypoints", list($(n).children("ul")[0]));
      break;
    case "dl": {
      const parts = [];
      $(n).children().each((_, k) => {
        if (k.name === "dt") parts.push(inl(k).trim());
        else parts[parts.length - 1] += "\n: " + inl(k).trim();
      });
      return parts.join("\n\n");
    }
    case "div":
      if (c.includes("table-wrap")) {
        const t = table($(n).children("table")[0]);
        return c.includes("wide-table") ? box("wide", t) : t;
      }
      if (c.includes("soon-card")) {
        return box("coming-soon", $(n).children().toArray().filter((k) => !cls(k).includes("soon-title")).map((k) => block(k, page)).join("\n\n"));
      }
      if (c.includes("case-cards")) {
        return box("cards", $(n).children("a").toArray().map((a) =>
          `- [${inl($(a).children(".cc-title")[0]).trim()}](${$(a).attr("href")}) — ${inl($(a).children(".cc-desc")[0]).trim()}`).join("\n"));
      }
      break;
    case "figure": {
      const parts = [];
      $(n).children().each((_, k) => {
        const kc = cls(k);
        if (k.name === "figcaption") parts.push(inl(k).trim());
        else if (kc.includes("figure-img")) {
          const img = $(k).find("img");
          const m = /^data:image\/(\w+);base64,(.*)$/.exec(img.attr("src"));
          const name = `${page}.${m[1]}`;
          images.push(name);
          fs.writeFileSync(path.join(ROOT, "content/images", name), Buffer.from(m[2], "base64"));
          parts.push(`![${escText(img.attr("alt"))}](../images/${name})`);
        } else if (kc.includes("phases") || kc.includes("ladder")) {
          const name = kc.includes("phases") ? "phases" : "ladder";
          out(`content/partials/${name}.html`, $.html(k) + "\n");
          parts.push(`{{> ${name}}}`);
        } else fail("unhandled figure child " + kc);
      });
      return box("figure", parts.join("\n\n"));
    }
  }
  fail(`unhandled block <${n.name} class="${c.join(" ")}"> in ${page}`);
}

fs.mkdirSync(path.join(ROOT, "content/images"), { recursive: true });
let count = 0;
$("article[data-page]").each((_, art) => {
  const id = $(art).attr("data-page");
  let fm, body;
  if (id === "home") {
    fm = `title: ${q($(art).find("h1").text().trim())}\nsubtitle: ${q($(art).find(".home-sub").text().trim())}`;
    const desc = $(art).find("p.home-desc").toArray().map((p) => lineSafe(inl(p).trim()));
    const note = $(art).find(".home-note > p").toArray().map((p) => lineSafe(inl(p).trim()));
    body = desc.join("\n\n") + "\n\n::: home-note\n" + note.join("\n\n") + "\n:::";
  } else {
    fm = `title: ${q($(art).children("h1").text().trim())}\nstatus: ${$(art).attr("data-status")}`;
    body = $(art).contents().toArray().map((n) => block(n, id)).filter((x) => x != null).join("\n\n");
  }
  out(`content/pages/${id}.md`, `---\n${fm}\n---\n\n${body}\n`);
  count++;
});
console.log(`Wrote ${count} pages, ${images.length} images, template, site.yml`);
